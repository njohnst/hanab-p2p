import { afterEach, describe, expect, it, vi } from "vitest";
import { gameUrl, parseGameReference } from "./routes";

describe("parseGameReference", () => {
  describe("room names", () => {
    it("accepts a room name as generated by readableUniqueId", () => {
      expect(parseGameReference("ExcitingHookwormPink")).toBe("ExcitingHookwormPink");
      expect(parseGameReference("OkOxRed")).toBe("OkOxRed");
    });

    it("ignores surrounding whitespace but keeps the case", () => {
      expect(parseGameReference("  ExcitingHookwormPink \n")).toBe("ExcitingHookwormPink");
      expect(parseGameReference("\tMuteDragonOrange")).toBe("MuteDragonOrange");
    });

    it("ignores brackets, quotes and punctuation around it", () => {
      expect(parseGameReference('"ExcitingHookwormPink"')).toBe("ExcitingHookwormPink");
      expect(parseGameReference("ExcitingHookwormPink.")).toBe("ExcitingHookwormPink");
      expect(parseGameReference("(ExcitingHookwormPink),")).toBe("ExcitingHookwormPink");
    });

    it.each([
      ["“ExcitingHookwormPink”"],
      ["‘ExcitingHookwormPink’"],
      ["„ExcitingHookwormPink“"],
      ["«ExcitingHookwormPink»"],
      ["« ExcitingHookwormPink »"],
      ["«\u00a0ExcitingHookwormPink\u00a0»"],
      ["«\u202fExcitingHookwormPink\u202f»"],
      ["‹ExcitingHookwormPink›"],
      ["*ExcitingHookwormPink*"],
      ["**ExcitingHookwormPink**"],
      ["_ExcitingHookwormPink_"],
      ["`ExcitingHookwormPink`"],
      ["“ExcitingHookwormPink”."],
    ])("ignores typographic quotes and chat formatting in %j", (input) => {
      expect(parseGameReference(input)).toBe("ExcitingHookwormPink");
    });

    it.each([
      ["\u200bExcitingHookwormPink"],
      ["\u200eExcitingHookwormPink\u200f"],
      ["\u2066ExcitingHookwormPink\u2069"],
      ["\u202aExcitingHookwormPink\u202c"],
      ["\ufeffExcitingHookwormPink"],
      ["Exciting\u200bHookworm\u00adPink"],
      ["\u200b“ExcitingHookwormPink”\u200b"],
    ])("ignores invisible characters in %j", (input) => {
      expect(parseGameReference(input)).toBe("ExcitingHookwormPink");
    });

    it("accepts the numbered ids hanab.cards generated from 2024 to 2026", () => {
      expect(parseGameReference("ExcitingHookwormPink-0")).toBe("ExcitingHookwormPink-0");
      expect(parseGameReference("ExcitingHookwormPink-12")).toBe("ExcitingHookwormPink-12");
    });

    it("rejects names that are not shaped like a room id", () => {
      // Room ids are case-sensitive: lower-casing them names another room.
      expect(parseGameReference("excitinghookwormpink")).toBeNull();
      expect(parseGameReference("Excitinghookwormpink")).toBeNull();
      expect(parseGameReference("EXCITINGHOOKWORMPINK")).toBeNull();
      expect(parseGameReference("Exciting Hookworm Pink")).toBeNull();
      expect(parseGameReference("Hello")).toBeNull();
      expect(parseGameReference("ExcitingHookwormPink-")).toBeNull();
      expect(parseGameReference("ExcitingHookwormPink-x")).toBeNull();
      expect(parseGameReference("ExcitingHookwormPink-0-1")).toBeNull();
    });
  });

  describe("game links", () => {
    it("reads gameId from a full GitHub Pages link", () => {
      expect(parseGameReference("https://user.github.io/hanabi-app/play/?gameId=ExcitingHookwormPink")).toBe(
        "ExcitingHookwormPink"
      );
    });

    it("reads gameId from a path, with or without a trailing slash", () => {
      expect(parseGameReference("/play?gameId=Foo")).toBe("Foo");
      expect(parseGameReference("/play/?gameId=Foo")).toBe("Foo");
      expect(parseGameReference("play/?gameId=Foo")).toBe("Foo");
      expect(parseGameReference("?gameId=Foo")).toBe("Foo");
    });

    it("reads gameId among other params, in any order", () => {
      expect(parseGameReference("/play/?as=bob&gameId=MuteDragonOrange&back-to-game=X")).toBe("MuteDragonOrange");
      expect(parseGameReference("https://example.com/play/?gameId=Foo&as=alice#top")).toBe("Foo");
    });

    it("reads gameId from a summary link", () => {
      expect(parseGameReference("https://user.github.io/hanabi-app/summary/?gameId=ThinFrogFuchsia")).toBe(
        "ThinFrogFuchsia"
      );
    });

    it("accepts links pasted without their scheme", () => {
      expect(parseGameReference("user.github.io/hanabi-app/play/?gameId=ThinFrogFuchsia")).toBe("ThinFrogFuchsia");
      expect(parseGameReference("localhost:3000/play/?gameId=ThinFrogFuchsia")).toBe("ThinFrogFuchsia");
    });

    it("accepts a link wrapped in angle brackets or followed by punctuation", () => {
      expect(parseGameReference("<https://example.com/play/?gameId=ThinFrogFuchsia>")).toBe("ThinFrogFuchsia");
      expect(parseGameReference("https://example.com/play/?gameId=ThinFrogFuchsia.")).toBe("ThinFrogFuchsia");
    });

    it.each([
      ["“https://user.github.io/hanabi-app/play/?gameId=MuteDragonOrange”"],
      ["« https://user.github.io/hanabi-app/play/?gameId=MuteDragonOrange »"],
      ["`https://user.github.io/hanabi-app/play/?gameId=MuteDragonOrange`"],
      ["*https://user.github.io/hanabi-app/play/?gameId=MuteDragonOrange*"],
      ["\u200bhttps://user.github.io/hanabi-app/play/?gameId=MuteDragonOrange\u200e"],
    ])("accepts a link in typographic quotes, chat formatting or invisible characters: %j", (input) => {
      expect(parseGameReference(input)).toBe("MuteDragonOrange");
    });

    it("reads a numbered gameId", () => {
      expect(parseGameReference("/play/?gameId=ExcitingHookwormPink-0")).toBe("ExcitingHookwormPink-0");
    });

    it("round-trips gameUrl", () => {
      expect(parseGameReference(gameUrl("RadicalPorcupineMagenta", { as: "bob" }))).toBe("RadicalPorcupineMagenta");
    });

    it("prefers gameId over the path", () => {
      expect(parseGameReference("https://hanab.cards/ExcitingHookwormPink?gameId=MuteDragonOrange")).toBe(
        "MuteDragonOrange"
      );
    });
  });

  describe("legacy hanab.cards links", () => {
    it("reads the id from /<Id>", () => {
      expect(parseGameReference("https://hanab.cards/ExcitingHookwormPink")).toBe("ExcitingHookwormPink");
      expect(parseGameReference("https://hanab.cards/ExcitingHookwormPink/")).toBe("ExcitingHookwormPink");
      expect(parseGameReference("hanab.cards/ExcitingHookwormPink")).toBe("ExcitingHookwormPink");
    });

    it("reads the id from /<Id>/summary", () => {
      expect(parseGameReference("https://hanab.cards/ExcitingHookwormPink/summary")).toBe("ExcitingHookwormPink");
      expect(parseGameReference("https://hanab.cards/ExcitingHookwormPink/summary/")).toBe("ExcitingHookwormPink");
    });

    it("reads numbered ids, as hanab.cards generated them from 2024 to 2026", () => {
      expect(parseGameReference("https://hanab.cards/ExcitingHookwormPink-0")).toBe("ExcitingHookwormPink-0");
      expect(parseGameReference("https://hanab.cards/ExcitingHookwormPink-3/summary")).toBe("ExcitingHookwormPink-3");
      expect(parseGameReference("hanab.cards/ExcitingHookwormPink-0")).toBe("ExcitingHookwormPink-0");
      expect(parseGameReference("Rematch: https://hanab.cards/ExcitingHookwormPink-1!")).toBe("ExcitingHookwormPink-1");
    });

    it("reads the id on any host and under any base path", () => {
      expect(parseGameReference("https://user.github.io/hanabi-app/ExcitingHookwormPink")).toBe("ExcitingHookwormPink");
      expect(parseGameReference("http://localhost:3000/ExcitingHookwormPink/summary?as=bob")).toBe(
        "ExcitingHookwormPink"
      );
      expect(parseGameReference("/ExcitingHookwormPink")).toBe("ExcitingHookwormPink");
    });

    it("does not take a page name or base path for an id", () => {
      expect(parseGameReference("https://hanab.cards/")).toBeNull();
      expect(parseGameReference("https://hanab.cards/summary")).toBeNull();
      expect(parseGameReference("https://user.github.io/hanabi-app/")).toBeNull();
      expect(parseGameReference("https://user.github.io/hanabi-app/join-game/")).toBeNull();
      expect(parseGameReference("https://user.github.io/hanabi-app/play/?gameId=")).toBeNull();
      expect(parseGameReference("https://user.github.io/Hanabi/")).toBeNull();
    });
  });

  describe("invitation messages", () => {
    it("finds the link in a pasted message", () => {
      expect(
        parseGameReference(
          "You're being invited to a game of Hanab 🎉 https://user.github.io/hanabi-app/play/?gameId=MuteDragonOrange"
        )
      ).toBe("MuteDragonOrange");
      expect(parseGameReference("Join us: https://hanab.cards/ExcitingHookwormPink!")).toBe("ExcitingHookwormPink");
    });

    it("finds a link in typographic quotes in a pasted message", () => {
      expect(parseGameReference("Join here: “https://user.github.io/hanabi-app/play/?gameId=MuteDragonOrange”")).toBe(
        "MuteDragonOrange"
      );
      expect(
        parseGameReference("Rejoins-nous : « https://user.github.io/hanabi-app/play/?gameId=MuteDragonOrange ».")
      ).toBe("MuteDragonOrange");
    });

    it("does not take a capitalised word of the message for a room name", () => {
      expect(parseGameReference("Join MyFriends tonight")).toBeNull();
      expect(parseGameReference("Join MyFriends at https://example.com/rules")).toBeNull();
    });
  });

  describe("garbage", () => {
    it.each([
      [""],
      ["   "],
      ["\n\t"],
      ["!!!"],
      ["hello world"],
      ["https://example.com"],
      ["https://example.com/some/page?query=1"],
      ["/play/?gameId=Foo%20Bar"],
      ["/play/?gameId=../secret"],
      ["javascript:alert(1)"],
      ["http://"],
      ["12345"],
    ])("returns null for %j", (input) => {
      expect(parseGameReference(input)).toBeNull();
    });

    it("does not accept a name or link truncated by a chat preview", () => {
      // "MuteDragonOr" names another room: better to say so than to join it.
      expect(parseGameReference("MuteDragonOr…")).toBeNull();
      expect(parseGameReference("https://user.github.io/hanabi-app/play/?gameId=MuteDragonOr…")).toBeNull();
    });

    it("returns null for a missing input", () => {
      expect(parseGameReference(undefined)).toBeNull();
      expect(parseGameReference(null)).toBeNull();
    });
  });

  describe("with a base path", () => {
    afterEach(() => {
      vi.unstubAllEnvs();
      vi.resetModules();
    });

    it("does not take the base path itself for an id", async () => {
      vi.stubEnv("NEXT_PUBLIC_BASE_PATH", "/HanabiApp");
      vi.resetModules();
      const routes = await import("./routes");

      expect(routes.parseGameReference("https://nick.github.io/HanabiApp/")).toBeNull();
      expect(routes.parseGameReference("https://nick.github.io/HanabiApp/ExcitingHookwormPink")).toBe(
        "ExcitingHookwormPink"
      );
      expect(routes.parseGameReference("https://nick.github.io/HanabiApp/play/?gameId=MuteDragonOrange")).toBe(
        "MuteDragonOrange"
      );
    });
  });
});
