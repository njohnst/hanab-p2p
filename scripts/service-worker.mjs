/**
 * The offline cache: a service worker that precaches the whole static export (see
 * docs/P2P_DESIGN.md, "Getting the app without internet").
 *
 * scripts/generate-sw.mjs runs after `next build`: it hashes the files of out/ and writes out/sw.js
 * with buildServiceWorker. src/lib/serviceWorker.ts registers it.
 *
 * - precacheKey, isPrecached, precacheHash and precacheManifest run at build time: which files are
 *   precached, under which key, and the version (a content hash of them all).
 * - cachePrefix, cacheUrl, routeRequest, parseRange and serviceWorker run IN the worker:
 *   buildServiceWorker inlines their source (Function.prototype.toString), so the tested code is the
 *   shipped code. They may only use each other and the worker's globals (no imports, no closure over
 *   this module), in syntax every browser with service workers runs.
 *
 * A precache key is a file's URL path relative to the worker's scope, decoded: "" for index.html,
 * "play/" for play/index.html, "_next/static/chunks/main-1a2b.js"... The worker resolves them against
 * self.registration.scope, so one build works under any base path.
 */
import { createHash } from "node:crypto";

/** The precache key of a file of the export (path relative to out/, with "/"), e.g. "play/" for "play/index.html". */
export function precacheKey(path) {
  if (path === "index.html") {
    return "";
  }

  return path.endsWith("/index.html") ? path.slice(0, -"index.html".length) : path;
}

/** Whether a file of the export is precached: everything but source maps, the worker itself and dotfiles. */
export function isPrecached(path) {
  return !path.endsWith(".map") && path !== "sw.js" && !path.split("/").some((segment) => segment.startsWith("."));
}

/** Hash of a file's content (the worker checks what it downloads against it): 16 hex digits of its SHA-256. */
export function precacheHash(content) {
  return createHash("sha256").update(content).digest("hex").slice(0, 16);
}

/**
 * The precache list and version of an export, from its files ({ path, hash }: path relative to
 * out/ with "/", hash from precacheHash). The list holds [key, hash] pairs sorted by key; the
 * version is a short hash of it, so it changes exactly when a precached file does.
 */
export function precacheManifest(files) {
  const precache = files
    .filter((file) => isPrecached(file.path))
    .map((file) => [precacheKey(file.path), file.hash])
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  const version = createHash("sha256").update(JSON.stringify(precache)).digest("hex").slice(0, 12);

  return { version, precache };
}

/** The source of sw.js for a precache manifest. */
export function buildServiceWorker({ version, precache }) {
  const inlined = [cachePrefix, cacheUrl, routeRequest, parseRange, serviceWorker].map((fn) => `${fn}\n`);
  const entries = precache.map((entry) => `  ${JSON.stringify(entry)},`).join("\n");

  return [
    "// Hanab's offline cache. Generated by scripts/generate-sw.mjs from scripts/service-worker.mjs: do not edit.",
    '"use strict";',
    "",
    ...inlined,
    `serviceWorker(${JSON.stringify(version)}, [\n${entries}\n]);`,
    "",
  ].join("\n");
}

/**
 * Prefix of the names of this app's caches for a worker scope. The scope is part of it because
 * caches belong to the origin, which several deployments can share (GitHub Pages project sites of
 * one owner): each one only ever touches its own caches.
 * Keep in sync with offlineCachePrefix in src/lib/serviceWorker.ts (a test checks).
 */
export function cachePrefix(scope) {
  return `hanab-offline:${scope}:`;
}

/** The URL a precache key is stored under: the key, URL-encoded, resolved against the scope. */
export function cacheUrl(key, scope) {
  return new URL(key.split("/").map(encodeURIComponent).join("/"), scope).href;
}

/**
 * How the worker answers a request ({ url, method, mode }, e.g. a Request), or null to leave it to
 * the browser. `precached` holds the precache keys (anything with has(key), e.g. a Set).
 * Only GET requests to the worker's origin, inside its scope, are answered:
 *
 * - { type: "page", key }: a navigation to a precached page or file (or to "<dir>/index.html").
 *   The query string is ignored, like static hosts do: /play/?gameId=X is the page "play/". The
 *   fragment (/nearby/#o=...) never reaches the worker.
 * - { type: "redirect", location }: a navigation to "<dir>" whose page is "<dir>/", keeping the
 *   query, as static hosts redirect it.
 * - { type: "notFound" }: any other navigation. The network answers, or the precached 404.html if it
 *   fails (it redirects legacy /<GameId> URLs client-side). Not the cache first: other sites can
 *   live under the scope (a GitHub Pages user site hosts the owner's project sites).
 * - { type: "asset", key }: any other request for a precached file or for anything under
 *   _next/static/ (hashed names: an open page of the previous version may still load its lazy
 *   chunks), from the caches, else the network.
 */
export function routeRequest(request, scope, precached) {
  if (request.method !== "GET") {
    return null;
  }

  const url = new URL(request.url);
  const root = new URL(scope);
  if (url.origin !== root.origin || !url.pathname.startsWith(root.pathname)) {
    return null;
  }

  let path;
  try {
    path = decodeURIComponent(url.pathname.slice(root.pathname.length));
  } catch (error) {
    return null;
  }

  if (request.mode !== "navigate") {
    return precached.has(path) || path.startsWith("_next/static/") ? { type: "asset", key: path } : null;
  }

  if (precached.has(path)) {
    return { type: "page", key: path };
  }

  const index = path === "index.html" || path.endsWith("/index.html") ? path.slice(0, -"index.html".length) : null;
  if (index !== null && precached.has(index)) {
    return { type: "page", key: index };
  }

  if (path !== "" && !path.endsWith("/") && precached.has(`${path}/`)) {
    return { type: "redirect", location: `${url.origin}${url.pathname}/${url.search}` };
  }

  return { type: "notFound" };
}

/**
 * The bytes a Range header asks for in a body of `size` bytes: { start, end } (inclusive),
 * "unsatisfiable" (answer 416), or null to answer with the whole body (no header, several ranges, or
 * a syntax not handled here: a server may always ignore Range).
 * Media elements send Range requests, and Safari only plays media answered with 206.
 */
export function parseRange(header, size) {
  const match = /^\s*bytes\s*=\s*(\d*)\s*-\s*(\d*)\s*$/i.exec(header || "");
  if (!match || (match[1] === "" && match[2] === "")) {
    return null;
  }

  if (match[1] === "") {
    // A suffix: the last N bytes.
    const length = Number(match[2]);
    return length === 0 || size === 0 ? "unsatisfiable" : { start: Math.max(0, size - length), end: size - 1 };
  }

  const start = Number(match[1]);
  const last = match[2] === "" ? size - 1 : Number(match[2]);
  if (last < start && match[2] !== "") {
    return null;
  }
  if (start >= size) {
    return "unsatisfiable";
  }

  return { start, end: Math.min(last, size - 1) };
}

/**
 * The service worker, run by sw.js as serviceWorker(version, precache) (see precacheManifest).
 *
 * - install: downloads every precached file into the cache of this version, bypassing the HTTP cache
 *   (cache: "reload") so that it cannot mix versions, a few files at a time. A file whose hash
 *   doesn't match (a host still serving the previous version) fails the install: the browser tries
 *   again later. Files whose hash is unchanged are copied from the other versions' caches instead of
 *   downloaded. A failed install leaves what it stored for the next attempt.
 * - Then it activates at once (skipWaiting), takes control of the open pages (clients.claim) and
 *   deletes this app's caches except this version's and the previous one's, which open pages may
 *   still load lazy chunks from. The new version is used from the next page load.
 * - fetch: see routeRequest. Pages and assets come from the caches. On localhost, pages come from
 *   the server while it answers (the cache when it doesn't): a production build and `next dev` can
 *   take turns on the same port, and the dev page then removes the worker
 *   (src/lib/serviceWorker.ts).
 */
export function serviceWorker(version, precache) {
  /** Response header holding precacheHash of a cached body. */
  const HASH_HEADER = "X-Hanab-Precache-Hash";
  /** Files downloaded at once while installing. */
  const BATCH_SIZE = 8;

  const scope = self.registration.scope;
  const prefix = cachePrefix(scope);
  const currentCache = prefix + version;
  const metaCache = `${prefix}meta`;
  /** Key, in metaCache, of the last versions activated (JSON array, oldest first). */
  const versionsUrl = cacheUrl("versions.json", scope);
  const precached = new Set(precache.map((entry) => entry[0]));
  const hostname = new URL(scope).hostname;
  const loopback =
    hostname === "localhost" || /\.localhost$/.test(hostname) || /^127\./.test(hostname) || hostname === "[::1]";

  /** Names of this app's version caches, this version's first. */
  async function versionCaches() {
    const names = (await caches.keys()).filter((name) => name.startsWith(prefix) && name !== metaCache);
    return names.filter((name) => name === currentCache).concat(names.filter((name) => name !== currentCache));
  }

  /** A precached file, from this version's cache or another version's. */
  async function cached(key) {
    const url = cacheUrl(key, scope);
    for (const name of await versionCaches()) {
      const response = await (await caches.open(name)).match(url);
      if (response) {
        return response;
      }
    }

    return undefined;
  }

  async function hash(body) {
    const digest = new Uint8Array(await crypto.subtle.digest("SHA-256", body));
    return Array.from(digest.slice(0, 8), (byte) => byte.toString(16).padStart(2, "0")).join("");
  }

  async function precacheFile(cache, otherCaches, key, expectedHash) {
    const url = cacheUrl(key, scope);
    const stored = await cache.match(url);
    if (stored && stored.headers.get(HASH_HEADER) === expectedHash) {
      return;
    }

    for (const name of otherCaches) {
      const previous = await (await caches.open(name)).match(url);
      if (previous && previous.headers.get(HASH_HEADER) === expectedHash) {
        await cache.put(url, previous);
        return;
      }
    }

    const response = await fetch(new Request(url, { cache: "reload", credentials: "same-origin" }));
    if (!response.ok) {
      throw new Error(`Precaching ${url} failed: HTTP ${response.status}`);
    }
    const body = await response.arrayBuffer();
    if ((await hash(body)) !== expectedHash) {
      throw new Error(`Precaching ${url} failed: not the expected content (is a deployment in progress?)`);
    }

    // A new response: the headers we need only, and never "redirected", which navigations refuse.
    const headers = new Headers({ [HASH_HEADER]: expectedHash });
    const type = response.headers.get("Content-Type");
    if (type) {
      headers.set("Content-Type", type);
    }
    await cache.put(url, new Response(body, { headers }));
  }

  async function install() {
    const cache = await caches.open(currentCache);
    const otherCaches = (await versionCaches()).filter((name) => name !== currentCache);
    for (let i = 0; i < precache.length; i += BATCH_SIZE) {
      const batch = precache.slice(i, i + BATCH_SIZE);
      // Let the whole batch settle: what it stored is kept for the next attempt.
      const results = await Promise.allSettled(
        batch.map((entry) => precacheFile(cache, otherCaches, entry[0], entry[1]))
      );
      const failure = results.find((result) => result.status === "rejected");
      if (failure) {
        throw failure.reason;
      }
    }

    await self.skipWaiting();
  }

  async function activate() {
    const meta = await caches.open(metaCache);
    let activated = [];
    try {
      const stored = await meta.match(versionsUrl);
      activated = stored ? await stored.json() : [];
    } catch (error) {
      activated = [];
    }

    const previous = (Array.isArray(activated) ? activated : []).filter((other) => other !== version).slice(-1);
    const kept = previous.concat(version);
    await meta.put(
      versionsUrl,
      new Response(JSON.stringify(kept), { headers: { "Content-Type": "application/json" } })
    );

    const stale = (await versionCaches()).filter((name) => kept.indexOf(name.slice(prefix.length)) === -1);
    await Promise.all(stale.map((name) => caches.delete(name)));
    await self.clients.claim();
  }

  /** A cached response cut to the request's Range header. */
  async function rangeResponse(response, header) {
    const body = await response.blob();
    const range = parseRange(header, body.size);
    if (range === null) {
      return new Response(body, { status: response.status, headers: response.headers });
    }
    if (range === "unsatisfiable") {
      return new Response(null, { status: 416, headers: { "Content-Range": `bytes */${body.size}` } });
    }

    const headers = new Headers(response.headers);
    headers.set("Content-Range", `bytes ${range.start}-${range.end}/${body.size}`);
    headers.set("Content-Length", String(range.end - range.start + 1));
    return new Response(body.slice(range.start, range.end + 1), {
      status: 206,
      statusText: "Partial Content",
      headers,
    });
  }

  async function respond(route, request) {
    if (route.type === "redirect") {
      return Response.redirect(route.location, 302);
    }

    if (route.type === "notFound") {
      try {
        return await fetch(request);
      } catch (error) {
        const notFound = await cached("404.html");
        if (notFound) {
          return notFound;
        }
        throw error;
      }
    }

    if (route.type === "page") {
      if (loopback) {
        try {
          return await fetch(request);
        } catch (error) {
          // The server is down: the cache below.
        }
      }

      return (await cached(route.key)) || fetch(request);
    }

    const response = await cached(route.key);
    if (!response) {
      return fetch(request);
    }

    const range = request.headers.get("Range");
    return range ? rangeResponse(response, range) : response;
  }

  self.addEventListener("install", (event) => {
    event.waitUntil(install());
  });

  self.addEventListener("activate", (event) => {
    event.waitUntil(activate());
  });

  self.addEventListener("fetch", (event) => {
    const request = event.request;
    // fetch() rejects these (requests made by DevTools): leave them to the browser.
    if (request.cache === "only-if-cached" && request.mode !== "same-origin") {
      return;
    }

    const route = routeRequest(request, scope, precached);
    if (route) {
      event.respondWith(respond(route, request));
    }
  });
}
